package core

import (
	"bytes"
	"encoding/json"
	"os"
	"testing"
	"time"
)

// wireContractPath is shared with the monitor module. Both modules sit under
// the repository root, so the same relative path resolves from either test.
const wireContractPath = "../../docs/wire/loopback.json"

// wireContractPayload is the one payload both sides of the loopback agree on.
// The daemon marshals it from its own wire types. The monitor decodes the same
// bytes into its own structs, so neither module imports the other.
type wireContractPayload struct {
	Runs    []WireRun         `json:"runs"`
	Event   WireEvent         `json:"event"`
	Control WireControlResult `json:"control"`
}

// contractFixture builds the payload from the real wire types. A rename of a
// JSON tag in any of them changes the generated bytes.
func contractFixture() wireContractPayload {
	return wireContractPayload{
		Runs: []WireRun{NewWireRun(&Run{
			ID:        RunID("run-contract-1"),
			TaskID:    TaskID("T-CONTRACT"),
			State:     RunWaitingCI,
			PRNumber:  42,
			HeadSHA:   "deadbeef",
			Branch:    "beacon/T-CONTRACT",
			Reason:    "checking CI",
			UpdatedAt: time.Date(2026, time.November, 25, 10, 0, 0, 0, time.UTC),
		})},
		Event: WireEvent{
			ID:    17,
			Type:  "idle",
			RunID: "run-contract-1",
			At:    "2026-11-25T10:00:00Z",
		},
		Control: NewWireControlResult(ControlApprove, RunID("run-contract-1")),
	}
}

// TestWireContractGolden pins the daemon side of the loopback wire. It fails
// when a wire tag or value changes. On drift it rewrites the golden file so the
// monitor test reads the new bytes and fails too, making the change visible on
// both sides without an import edge.
func TestWireContractGolden(t *testing.T) {
	got, err := json.MarshalIndent(contractFixture(), "", "  ")
	if err != nil {
		t.Fatalf("marshal wire contract: %v", err)
	}
	got = append(got, '\n')

	committed, err := os.ReadFile(wireContractPath)
	if err != nil {
		t.Fatalf("read %s: %v", wireContractPath, err)
	}
	if bytes.Equal(committed, got) {
		return
	}
	if err := os.WriteFile(wireContractPath, got, 0o644); err != nil {
		t.Fatalf("update %s: %v", wireContractPath, err)
	}
	t.Fatalf("wire contract drift: %s was regenerated\ncommitted:\n%s\ngenerated:\n%s", wireContractPath, committed, got)
}
